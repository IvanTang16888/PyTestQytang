# ============================================================
# Day02 任務 1：正則解析交換機 MAC 位址表的一行
# 原始資料（show mac address-table 的一行）：
#   VLAN   MAC 位址          類型        埠
#   166    54a2.74f7.0326    DYNAMIC     Gi1/0/11
# ============================================================

import re

mac_table = '166    54a2.74f7.0326    DYNAMIC     Gi1/0/11'

# re.match：從字串「開頭」開始比對
#
# 規則拆解：
#   ^                    → 字串開頭
#   (\d{1,4})            → 組 1：VLAN，1~4 位數字（VLAN 範圍 1~4094）
#   \s+                  → 一個以上的空白（欄位之間空格數不固定，所以用 +）
#   ([0-9a-fA-F]{4}\.    → 組 2：MAC，4 個 16 進位字元 + 一個點
#    [0-9a-fA-F]{4}\.        \. 要跳脫，因為單獨的 . 在正則裡代表「任意字元」
#    [0-9a-fA-F]{4})
#   \s+
#   (\w+)                → 組 3：類型，\w = 英文字母/數字/底線 → DYNAMIC
#   \s+
#   (\S+)                → 組 4：埠，\S = 非空白 → Gi1/0/11（包含 /，所以不能用 \w）
#   $                    → 字串結尾
m = re.match(r"^(\d{1,4})\s+([0-9a-fA-F]{4}\.[0-9a-fA-F]{4}\.[0-9a-fA-F]{4})\s+(\w+)\s+(\S+)$",mac_table)


# "{:<6}: {}".format(標題, 值)
#   {:<6} → 標題靠左佔 6 格，讓冒號對齊
#   {}    → 值
print("{:<6}: {}".format("VLAN", m.group(1)))
print("{:<6}: {}".format("MAC",m.group(2)))
print("{:<6}: {}".format("Type",m.group(3)))
print("{:<6}: {}".format("Port",m.group(4)))

# 執行結果：
# VLAN  : 166
# MAC   : 54a2.74f7.0326
# Type  : DYNAMIC
# Port  : Gi1/0/11
