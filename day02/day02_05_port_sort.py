# ============================================================
# Day02 任務 5：把介面列表「依數字大小」排序
# 格式 eth 1/101/X/Y → 先比 X，X 一樣再比 Y
# ============================================================

import re

port_list = [
    'eth 1/101/1/42',
    'eth 1/101/1/26',
    'eth 1/101/1/23',
    'eth 1/101/1/7',
    'eth 1/101/2/46',
    'eth 1/101/1/34',
    'eth 1/101/1/18',
    'eth 1/101/1/13',
    'eth 1/101/1/32',
    'eth 1/101/1/25',
    'eth 1/101/1/45',
    'eth 1/101/2/8',
]

# 為什麼不能直接 port_list.sort()？
#   字串排序是「一個字元一個字元」比較：'1/13' 的 '1' 比 '1/7' 的 '7' 小
#   → 結果會變成 13, 18, 23 ... 7（7 跑到最後面），不是我們要的
#   所以要把數字抓出來、轉成 int 再比
#
# list.sort(key=函式)：排序前，先把每個元素丟進「函式」，用函式的回傳值來比大小
#   （sort 會直接修改原本的列表；sorted() 則是回傳一個新列表）
#
# lambda x: ...  → 沒有名字的小函式，x 就是列表裡的每一個元素
#
# 由內往外拆解，以 x = 'eth 1/101/1/42' 為例：
#   re.match(r"eth \d+/\d+/(\d+)/(\d+)", x) → 只把第 3、4 段數字放進捕獲組
#   .groups()                              → ('1', '42')   ← 還是字串
#   map(int, ...)                          → 把每個元素都套用 int() → 1, 42
#   tuple(...)                             → (1, 42)        ← 變成整數元組
#
# 元組比大小：先比第 1 個元素，一樣的話再比第 2 個
#   (1, 7) < (1, 13) < (1, 45) < (2, 8) < (2, 46)
port_list.sort(key=lambda x: tuple(map(int, re.match(r"eth \d+/\d+/(\d+)/(\d+)", x).groups())))
print(port_list)

# 執行結果：
# ['eth 1/101/1/7', 'eth 1/101/1/13', 'eth 1/101/1/18', ..., 'eth 1/101/1/45', 'eth 1/101/2/8', 'eth 1/101/2/46']
