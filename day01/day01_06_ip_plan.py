# ============================================================
# Day01 任務 6：列表 + 字典 + f-string 對齊 —— 印出 IP 規劃表
# ============================================================

# devices 是一個「列表」[ ]，裡面每個元素是一個「字典」{ }
# 字典用 key 取值，例如 devices[0]["name"] → "CoreSwitch"
devices = [
    {"name": "CoreSwitch", "ip": "10.1.1.1", "role": "核心交换机"},
    {"name": "Firewall", "ip": "10.1.1.2", "role": "防火墙"},
    {"name": "WLC", "ip": "10.1.1.3", "role": "无线控制器"},
]

# 表頭（手動用空格排好位置）
print("设备名称          管理地址          角色")

# for 迴圈：一次取出一台設備（一個字典），放進變數 a
for a in devices:
    # f-string：字串前面加 f，{ } 裡面可以直接放變數
    # {值:<18} 的意思：靠左對齊，固定佔 18 格，不夠的補空格
    # 注意：f-string 外層用雙引號 "，裡面取 key 就要用單引號 'name'
    print( f"{a['name']:<18}{a['ip']:<18}{a['role']}")

# 執行結果：
# 设备名称          管理地址          角色
# CoreSwitch        10.1.1.1          核心交换机
# Firewall          10.1.1.2          防火墙
# WLC               10.1.1.3          无线控制器
