# ============================================================
# Day01 任務 2：字串切片 —— 把介面名稱拆成「類型」和「編號」
# 例如 "GigabitEthernet0/0/1" → 類型 GigabitEthernet、編號 0/0/1
# ============================================================

interface = "GigabitEthernet0/0/1"

# 切片語法：字串[開始:結束]，包含「開始」，不包含「結束」
# 索引從 0 開始，"GigabitEthernet" 剛好 15 個字元 → 索引 0~14
aa = interface [0:15]          # 取第 0~14 個字元 → "GigabitEthernet"
#print(aa)

# 負數索引從後面數：-1 是最後一個字元
# [-5:] = 從倒數第 5 個字元取到最後 → "0/0/1"
bb = interface [-5:]
#print(bb)

# 用 + 把字串接起來再印出（+ 兩邊都必須是字串）
print('接口类型:'+aa)
print('接口编号:'+bb)

# 執行結果：
# 接口类型:GigabitEthernet
# 接口编号:0/0/1
