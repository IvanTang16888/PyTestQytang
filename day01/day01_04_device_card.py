# Day01 任務 4：變數 + 字串串接 —— 印出一張「設備資訊卡」
# ============================================================

# 把設備資訊分別存進變數（變數名 = 值）
hostname = "C8Kv1"
ip = "192.168.1.1"
vendor = "Cisco"
model = "C8000v"
os_version = "IOS-XE 17.3.4"

# 標題列
print('========== 设备信息 ==========')

# 用 + 把「欄位名稱」和「變數」接起來
# 欄位名稱後面手動補空格，讓冒號後面的值對齊在同一欄
# （「设备名称」是中文，每個中文字在終端機佔 2 格，所以空格數跟英文欄位不一樣）
print('设备名称:   '+ hostname)
print('IP:         '+ip)
print('Vendor:     '+vendor)
print('Model:      '+model)
print('OS Version: '+os_version)

# 執行結果：
# ========== 设备信息 ==========
# 设备名称:   C8Kv1
# IP:         192.168.1.1
# Vendor:     Cisco
# Model:      C8000v
# OS Version: IOS-XE 17.3.4
